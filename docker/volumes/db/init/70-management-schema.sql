-- Who may change a fork and everything in it: its creator, if still a
-- contributor, or a curator. SECURITY INVOKER: forks are readable by everyone.
CREATE OR REPLACE FUNCTION management.can_edit_fork(p_fork_id integer) RETURNS boolean
    LANGUAGE sql STABLE
    AS $$
    SELECT shared.is_curator()
        OR (shared.is_contributor() AND EXISTS (
                SELECT 1 FROM management.forks f
                 WHERE f.fork_id = p_fork_id AND f.created_by = auth.uid()::text));
$$;

COMMENT ON FUNCTION management.can_edit_fork(integer) IS
    'True when the caller may change the fork, its features, marks, run parameters and lock: curator, or the contributor who created it.';

ALTER TABLE management.areas            ENABLE ROW LEVEL SECURITY;
ALTER TABLE management.feature_types    ENABLE ROW LEVEL SECURITY;
ALTER TABLE management.forks            ENABLE ROW LEVEL SECURITY;
ALTER TABLE management.features         ENABLE ROW LEVEL SECURITY;
ALTER TABLE management.thinning_trees   ENABLE ROW LEVEL SECURITY;
ALTER TABLE management.thinning_runs    ENABLE ROW LEVEL SECURITY;
ALTER TABLE management.fork_locks       ENABLE ROW LEVEL SECURITY;
ALTER TABLE shared.management_events_trees ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
    -- schema, table, policy label, INSERT check, UPDATE/DELETE condition
    p record;
BEGIN
    FOR p IN SELECT * FROM (VALUES
        ('management', 'areas', 'management areas',
         'shared.is_contributor() AND created_by = auth.uid()::text',
         'shared.is_curator() OR (shared.is_contributor() AND created_by = auth.uid()::text)'),
        ('management', 'forks', 'forks',
         'shared.is_contributor() AND created_by = auth.uid()::text',
         'shared.is_curator() OR (shared.is_contributor() AND created_by = auth.uid()::text)'),
        ('management', 'features', 'management features',
         'management.can_edit_fork(fork_id)', 'management.can_edit_fork(fork_id)'),
        ('management', 'thinning_trees', 'thinning marks',
         'management.can_edit_fork(fork_id)', 'management.can_edit_fork(fork_id)'),
        ('management', 'thinning_runs', 'thinning runs',
         'management.can_edit_fork(fork_id)', 'management.can_edit_fork(fork_id)'),
        ('management', 'fork_locks', 'fork locks',
         'management.can_edit_fork(fork_id)', 'management.can_edit_fork(fork_id)')
    ) AS v(sch, tbl, label, ins, upd)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = p.sch AND tablename = p.tbl
                         AND policyname = upper(left(p.label, 1)) || substr(p.label, 2) || ' are viewable by everyone') THEN
            EXECUTE format('CREATE POLICY %I ON %I.%I FOR SELECT USING (true)',
                           upper(left(p.label, 1)) || substr(p.label, 2) || ' are viewable by everyone', p.sch, p.tbl);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = p.sch AND tablename = p.tbl
                         AND policyname = 'Contributors can create ' || p.label) THEN
            EXECUTE format('CREATE POLICY %I ON %I.%I FOR INSERT TO authenticated WITH CHECK (%s)',
                           'Contributors can create ' || p.label, p.sch, p.tbl, p.ins);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = p.sch AND tablename = p.tbl
                         AND policyname = 'Owners and curators can update ' || p.label) THEN
            EXECUTE format('CREATE POLICY %I ON %I.%I FOR UPDATE TO authenticated USING (%s) WITH CHECK (%s)',
                           'Owners and curators can update ' || p.label, p.sch, p.tbl, p.upd, p.upd);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = p.sch AND tablename = p.tbl
                         AND policyname = 'Owners and curators can delete ' || p.label) THEN
            EXECUTE format('CREATE POLICY %I ON %I.%I FOR DELETE TO authenticated USING (%s)',
                           'Owners and curators can delete ' || p.label, p.sch, p.tbl, p.upd);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = p.sch AND tablename = p.tbl
                         AND policyname = 'Service role can manage all ' || p.label) THEN
            EXECUTE format('CREATE POLICY %I ON %I.%I TO service_role USING (true) WITH CHECK (true)',
                           'Service role can manage all ' || p.label, p.sch, p.tbl);
        END IF;
    END LOOP;

    -- feature_types: a fixed lookup, read-only for users
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'management' AND tablename = 'feature_types'
                     AND policyname = 'Management feature types are viewable by everyone') THEN
        CREATE POLICY "Management feature types are viewable by everyone"
            ON management.feature_types FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'management' AND tablename = 'feature_types'
                     AND policyname = 'Service role can manage all management feature types') THEN
        CREATE POLICY "Service role can manage all management feature types"
            ON management.feature_types TO service_role USING (true) WITH CHECK (true);
    END IF;

    -- management_events_trees: like the event it belongs to (any contributor)
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'shared' AND tablename = 'management_events_trees'
                     AND policyname = 'Management tree links are viewable by everyone') THEN
        CREATE POLICY "Management tree links are viewable by everyone"
            ON shared.management_events_trees FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'shared' AND tablename = 'management_events_trees'
                     AND policyname = 'Contributors can manage management tree links') THEN
        CREATE POLICY "Contributors can manage management tree links"
            ON shared.management_events_trees TO authenticated
            USING (shared.is_contributor()) WITH CHECK (shared.is_contributor());
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'shared' AND tablename = 'management_events_trees'
                     AND policyname = 'Service role can manage all management tree links') THEN
        CREATE POLICY "Service role can manage all management tree links"
            ON shared.management_events_trees TO service_role USING (true) WITH CHECK (true);
    END IF;
END $$;


