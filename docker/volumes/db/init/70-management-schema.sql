    p_fork_id    integer,
    p_session_id text,
    p_stale      interval DEFAULT interval '10 minutes'
) RETURNS TABLE (fork_id integer, locked_by character varying, locked_at timestamptz)
    LANGUAGE sql
    AS $$ SELECT * FROM management.fork_lock_acquire(p_fork_id, NULL, p_session_id, p_stale); $$;

