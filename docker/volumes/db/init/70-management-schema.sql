CREATE OR REPLACE FUNCTION management.update_updated_at_column() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

-- A fork's base variant and scenario must be on its area's site.
CREATE OR REPLACE FUNCTION management.check_fork_site() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
    v_site integer;
BEGIN
    SELECT location_id INTO v_site FROM management.areas WHERE area_id = NEW.area_id;

    IF NOT EXISTS (SELECT 1 FROM shared.variants
                   WHERE variant_id = NEW.base_variant_id AND location_id = v_site) THEN
        RAISE EXCEPTION 'base_variant_id % is not on the site of area %',
            NEW.base_variant_id, NEW.area_id
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    IF NEW.scenario_id IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM shared.scenarios
                       WHERE scenario_id = NEW.scenario_id AND location_id = v_site) THEN
        RAISE EXCEPTION 'scenario_id % is not on the site of area %',
            NEW.scenario_id, NEW.area_id
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    RETURN NEW;
END;
$$;

-- A mark must name a tree of the fork's base variant (tree_entity_id has no
-- unique constraint to point a foreign key at).
CREATE OR REPLACE FUNCTION management.check_thinning_tree() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
    v_variant integer;
    v_entity  uuid;
BEGIN
    SELECT base_variant_id INTO v_variant FROM management.forks WHERE fork_id = NEW.fork_id;

    FOREACH v_entity IN ARRAY ARRAY[NEW.tree_entity_id, NEW.z_tree_entity_id] LOOP
        CONTINUE WHEN v_entity IS NULL;
        IF NOT EXISTS (SELECT 1 FROM trees.trees
                       WHERE tree_entity_id = v_entity AND variant_id = v_variant) THEN
            RAISE EXCEPTION 'tree_entity_id % is not in base variant % of fork %',
                v_entity, v_variant, NEW.fork_id
                USING ERRCODE = 'foreign_key_violation';
        END IF;
    END LOOP;

    RETURN NEW;
END;
$$;

