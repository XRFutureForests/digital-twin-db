COMMENT ON TABLE management.feature_types IS
    'Kinds of features drawn in a fork. Fixed ids, read by the Shiny app.';


CREATE TABLE IF NOT EXISTS management.forks (
    fork_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id         integer NOT NULL
                    REFERENCES management.areas(area_id) ON DELETE CASCADE,
    base_variant_id integer NOT NULL REFERENCES shared.variants(variant_id),
    scenario_id     integer REFERENCES shared.scenarios(scenario_id),
    description     text,
    is_committed    boolean NOT NULL DEFAULT false,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz,
    created_by      character varying(200)
);

CREATE INDEX IF NOT EXISTS idx_management_forks_area
    ON management.forks (area_id);
CREATE INDEX IF NOT EXISTS idx_management_forks_base_variant
    ON management.forks (base_variant_id);

COMMENT ON TABLE management.forks IS
    'Planning variant ("fork") of a management area.';
COMMENT ON COLUMN management.forks.base_variant_id IS
    'shared.variants row whose trees the plan was made on. Same site as the area.';
COMMENT ON COLUMN management.forks.scenario_id IS
    'Optional shared.scenarios row the plan works towards (e.g. crop_tree_thinning). Same site as the area.';
COMMENT ON COLUMN management.forks.is_committed IS
    'The fork has been applied. Marks of a committed fork no longer show in v_thinning_open.';


CREATE TABLE IF NOT EXISTS management.features (
    feature_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fork_id         integer NOT NULL
                    REFERENCES management.forks(fork_id) ON DELETE CASCADE,
    feature_type_id smallint NOT NULL
                    REFERENCES management.feature_types(feature_type_id),
    skid_width_m    double precision,
    skid_distance_m double precision,
    geom            extensions.geometry(Geometry, 4326) NOT NULL,
    description     text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    created_by      character varying(200)
);

CREATE INDEX IF NOT EXISTS idx_management_features_geom
    ON management.features USING gist (geom);
CREATE INDEX IF NOT EXISTS idx_management_features_fork
    ON management.features (fork_id);

COMMENT ON TABLE management.features IS
    'Areas and lines drawn in a fork: skid roads, windthrow/biotic damage polygons, crop-tree buffers.';


-- The figures are redundant to the tree on purpose: they record what the
-- decision was based on (Df-24 target diameter, spacing radius, Hegyi index),
-- even after the stand has changed.
CREATE TABLE IF NOT EXISTS management.thinning_trees (
    fork_id          integer NOT NULL
                     REFERENCES management.forks(fork_id) ON DELETE CASCADE,
    tree_entity_id   uuid NOT NULL,
    -- 'z'       = crop tree (Zukunftsbaum), stays and is favoured
    -- 'removal' = competitor, marked for removal
    role             text NOT NULL CHECK (role IN ('z', 'removal')),
    -- the crop tree a removal favours (role = 'removal' only)
    z_tree_entity_id uuid,
    quality_rvr      character(1),
    dbh_cm           double precision,
    df24_group       text,
    target_dbh_cm    double precision,
    spacing_radius_m double precision,
    hegyi_index      double precision,
    hegyi_share      double precision,
    created_at       timestamptz NOT NULL DEFAULT now(),
    created_by       character varying(200),
    PRIMARY KEY (fork_id, tree_entity_id)
);

CREATE INDEX IF NOT EXISTS idx_management_thinning_trees_entity
    ON management.thinning_trees (tree_entity_id);

COMMENT ON TABLE management.thinning_trees IS
    'Crop trees and removal marks per fork. A mark never changes the tree; it takes effect when the harvest is recorded.';
COMMENT ON COLUMN management.thinning_trees.tree_entity_id IS
    'trees.trees.tree_entity_id: the tree across all its versions. Must exist in the fork''s base variant.';


CREATE TABLE IF NOT EXISTS management.thinning_runs (
    fork_id    integer PRIMARY KEY
               REFERENCES management.forks(fork_id) ON DELETE CASCADE,
    params     jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by character varying(200)
);

COMMENT ON TABLE management.thinning_runs IS
    'Parameters of the thinning run per fork (target diameter per species, upper storey, Hegyi factor, quality classes), so a saved thinning can be reopened with the values it was computed with.';


-- Check-out lock per fork. The Shiny app replaces a fork as a whole on save,
-- so two people editing the same fork would silently overwrite each other. A
-- table rather than pg_advisory_lock: the app shares one database session
-- between all its users, and the lock must survive minutes to hours of editing.
-- Not a guarantee -- an offline field device cannot hold it and a stale lock
-- must be taken over -- so the app also compares a fingerprint on save.
CREATE TABLE IF NOT EXISTS management.fork_locks (
    fork_id      integer PRIMARY KEY
                 REFERENCES management.forks(fork_id) ON DELETE CASCADE,
    locked_by    character varying(200) NOT NULL,
    -- distinguishes two windows of the same person, so a session can take its
    -- own lock again instead of locking itself out
    session_id   text NOT NULL,
    locked_at    timestamptz NOT NULL DEFAULT now(),
    -- refreshed while editing; a lock whose heartbeat stops is stale and can
    -- be taken over
    heartbeat_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_management_fork_locks_heartbeat
    ON management.fork_locks (heartbeat_at);

COMMENT ON TABLE management.fork_locks IS
    'Check-out lock per fork, held by the editing session. Taken, refreshed and released through management.fork_lock_acquire/_heartbeat/_release.';
COMMENT ON COLUMN management.fork_locks.locked_by IS
    'auth.uid() of the holder; for a caller without a user token, the name it passed.';


-- Which trees an executed management event removed, and why. The counterpart
-- of shared.disturbance_events_trees; tree_id is the row the event wrote (the
-- 'harvested' version).
CREATE TABLE IF NOT EXISTS shared.management_events_trees (
    management_event_id integer NOT NULL
                        REFERENCES shared.management_events(management_event_id) ON DELETE CASCADE,
    tree_id             integer NOT NULL
                        REFERENCES trees.trees(tree_id) ON DELETE CASCADE,
    harvest_cause       character varying(50)
                        CHECK (harvest_cause IN ('planned', 'windthrow', 'biotic', 'skid_road')),
    fork_id             integer
                        REFERENCES management.forks(fork_id) ON DELETE SET NULL,
    notes               text,
    PRIMARY KEY (management_event_id, tree_id)
);

CREATE INDEX IF NOT EXISTS idx_mgmt_events_trees_tree
    ON shared.management_events_trees (tree_id);
CREATE INDEX IF NOT EXISTS idx_mgmt_events_trees_fork
    ON shared.management_events_trees (fork_id);

COMMENT ON TABLE shared.management_events_trees IS
    'Links management events to the individual trees they affected.';
COMMENT ON COLUMN shared.management_events_trees.harvest_cause IS
    'Why the tree was removed: planned (regular management), windthrow, biotic, skid_road. NULL for events that do not remove the tree.';
COMMENT ON COLUMN shared.management_events_trees.fork_id IS
    'The fork the removal was planned in, if any.';


