-- -----------------------------------------------------------------------------
-- 5. Fork locks
-- -----------------------------------------------------------------------------
-- SECURITY INVOKER, so the fork_locks policies decide who may lock. A caller
-- with a user token is recorded as auth.uid(); p_user is used only without one
-- (the Shiny app on a direct connection), so a token holder cannot pose as
-- someone else. Parameter order as in the prototype, which the app calls.

-- Take the lock. One statement, so two concurrent attempts cannot both win.
-- Taken over only when it is this session's own or stale.
-- Returns the row when the lock is now ours, otherwise no row.
CREATE OR REPLACE FUNCTION management.fork_lock_acquire(
    p_fork_id    integer,
    p_user       text,
    p_session_id text,
    p_stale      interval DEFAULT interval '10 minutes'
) RETURNS TABLE (fork_id integer, locked_by character varying, locked_at timestamptz)
    LANGUAGE sql
    AS $$
    INSERT INTO management.fork_locks AS l (fork_id, locked_by, session_id)
    VALUES (p_fork_id, COALESCE(auth.uid()::text, p_user, 'system'), p_session_id)
    ON CONFLICT (fork_id) DO UPDATE
       SET locked_by    = EXCLUDED.locked_by,
           session_id   = EXCLUDED.session_id,
           locked_at    = now(),
           heartbeat_at = now()
     WHERE l.session_id = EXCLUDED.session_id
        OR l.heartbeat_at < now() - p_stale
    RETURNING l.fork_id, l.locked_by, l.locked_at;
$$;

-- Keep the lock fresh. Only the holding session; returns false otherwise.
CREATE OR REPLACE FUNCTION management.fork_lock_heartbeat(
    p_fork_id    integer,
    p_session_id text
) RETURNS boolean
    LANGUAGE sql
    AS $$
    WITH beat AS (
        UPDATE management.fork_locks
           SET heartbeat_at = now()
         WHERE fork_id = p_fork_id AND session_id = p_session_id
        RETURNING 1
    )
    SELECT count(*) > 0 FROM beat;
$$;

-- Release the lock. Only the holding session; another session's lock stays.
CREATE OR REPLACE FUNCTION management.fork_lock_release(
    p_fork_id    integer,
    p_session_id text
) RETURNS boolean
    LANGUAGE sql
    AS $$
    WITH released AS (
        DELETE FROM management.fork_locks
         WHERE fork_id = p_fork_id AND session_id = p_session_id
        RETURNING 1
    )
    SELECT count(*) > 0 FROM released;
$$;

REVOKE ALL ON FUNCTION management.fork_lock_acquire(integer, text, text, interval) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION management.fork_lock_heartbeat(integer, text) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION management.fork_lock_release(integer, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION management.fork_lock_acquire(integer, text, text, interval) TO authenticated, service_role;
