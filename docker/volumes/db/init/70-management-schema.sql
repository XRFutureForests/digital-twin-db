CREATE TABLE IF NOT EXISTS management.areas (
    area_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id integer NOT NULL REFERENCES shared.locations(location_id),
    geom        extensions.geometry(Polygon, 4326) NOT NULL,
    description text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz,
    created_by  character varying(200)
