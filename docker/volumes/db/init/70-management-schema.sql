-- =============================================================================
-- management: planning areas, planning variants ("forks"), thinning, fork locks
-- =============================================================================
-- Ports the planning schema of the Shiny app (twinfrontend) from the
-- simple-postgres prototype (digital-twin-feature-simple-postgres, init files
-- 10, 12 and 16) into this database. A forester draws a management area, plans
-- one or more forks on it -- skid roads, windthrow/biotic damage polygons,
-- crop-tree buffers -- and marks crop trees and trees for removal.
--
-- Decided 2026-10-30 (owner), each deliberately different from the prototype:
--
--   * Planning never changes a tree. A mark lives in management.thinning_trees
--     only. The prototype gave a marked tree a new version with one of four
--     'harvesting ...' statuses (tree_status_id 7-10) when a fork was applied;
--     here only the actual harvest writes the tree -- a new row with status
--     'harvested' -- together with a shared.management_events row. Why the tree
--     came out (planned, windthrow, biotic, skid road) is recorded per tree in
--     shared.management_events_trees.harvest_cause, the counterpart of
--     shared.disturbance_events_trees, so tree_status keeps one 'harvested'.
--   * A mark points at trees.trees.tree_entity_id, the identity a tree keeps
--     across all its versions, not at one row. A tree that is re-measured while
--     the fork is open keeps its marks. tree_entity_id is not unique in
--     trees.trees, so a trigger checks it instead of a foreign key.
--   * An area belongs to a site (location_id), and a fork records the variant
--     it was planned on (base_variant_id) and optionally the scenario it plans
--     towards (e.g. crop_tree_thinning). A trigger keeps all three on the
--     area's site.
--   * Users and rights follow this database, not the prototype's free-text
--     names: created_by is auth.uid() (or 'system') via shared.set_created_by();
--     everyone reads; contributors create; the creator or a curator changes and
--     deletes. Features, marks and run parameters inherit the right from their
--     fork (management.can_edit_fork).
--   * Names follow this database's conventions (plural tables, is_ booleans,
--     unit suffixes): management_area -> areas, mng_id -> area_id,
--     management_fork -> forks, committed -> is_committed, management_feature ->
--     features, skid_width/skid_dist -> skid_width_m/skid_distance_m,
--     thinning_tree -> thinning_trees, ziel_bhd -> target_dbh_cm,
--     spacing_radius -> spacing_radius_m, fork_lock -> fork_locks.
--
-- Geometry stays EPSG:4326 like every geometry column here (see
-- shared.locations.crs_epsg for the projected frame of a site).
--
-- PostgREST: the schema itself stays out of PGRST_DB_SCHEMAS. It is published
-- through security_invoker views in public, single-table and therefore
-- auto-updatable, so RLS on the base tables decides and a write RLS filters out
-- reports 0 rows (cf. 20261030110000_view_triggers_report_rls_skips).
--
-- NOT HERE: applying a fork (writing the harvested tree rows, the event and its
-- tree links). That depends on how tree versions are written, which is not
-- settled yet.
--
-- Mirrored to init 70-management-schema.sql.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS management;

COMMENT ON SCHEMA management IS
    'Forest management planning: areas, planning variants (forks), drawn features, '
    'crop-tree and removal marks, fork locks. Planning never changes trees.trees.';

GRANT USAGE ON SCHEMA management TO anon, authenticated, service_role;


